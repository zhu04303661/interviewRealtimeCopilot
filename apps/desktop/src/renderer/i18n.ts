// One interface language at a time: English strings are the keys, ZH maps them to Chinese.
// Components call t('English text'); useUiLang() re-renders when the language changes.
import { useEffect, useState } from 'react';

export type UiLang = 'en' | 'zh';

let current: UiLang = 'en';
const listeners = new Set<() => void>();

/** Stored pref ('', 'auto', 'en', 'zh') → the effective language; unset follows the system. */
export function resolveUiLang(pref: string | null | undefined): UiLang {
  return pref === 'en' || pref === 'zh' ? pref : navigator.language.startsWith('zh') ? 'zh' : 'en';
}

export function setUiLang(lang: UiLang): void {
  if (lang !== current) { current = lang; listeners.forEach((f) => f()); }
}

/** Re-render the calling component whenever the UI language changes. */
export function useUiLang(): UiLang {
  const [, bump] = useState(0);
  useEffect(() => {
    const onChange = () => bump((n) => n + 1);
    listeners.add(onChange);
    return () => { listeners.delete(onChange); };
  }, []);
  return current;
}

